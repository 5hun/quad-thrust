"""Restore OTR_MODE.C's help books and ROAD.TIM examples from HOVER.PAC."""
import json
import sys
from convert_models import OUT, ROOT, pixel, png, rgba

names = 'INTRO RADDER MOVE BOOSTER TURBO BRAKE SLASTER LUSTER EXCEL BETA JUSTER ALPHA SUZUKI MODES SIGN REPLAY ABOUT STAFF'.split()
books = {}
for name in names:
    lines = (ROOT / 'extracted' / (name + '.TXT')).read_text('cp932').splitlines()
    assert lines[-1] == 'END'
    lines = lines[:-1]
    assert len(lines) <= 96 and all(len(line) <= 16 for line in lines)
    if name == 'ABOUT':
        # book() replaces line 30 with the current release version.
        lines[30] = '　　　Ｖｅｒ　１．２００'
    books[name.lower()] = lines
if '--assets-only' not in sys.argv:
    (ROOT / 'src/help-data.ts').write_text(
        '// Original help TXT files, decoded from CP932. Generated by tools/convert_help.py.\n'
        + 'export const HELP_BOOKS: Record<string, string[]> = '
        + json.dumps(books, ensure_ascii=False, indent=2) + ';\n'
    )
# draw_wall: ROAD.TIM, page 0x95 / CLUT (0,484), modulated RGB 160,155,140.
wall = bytearray()
for y in range(32):
    for x in range(32):
        color = rgba(pixel(0x95, 484 << 6, x, y))
        wall.extend([min(255, color[i] * [160, 155, 140][i] // 128) for i in range(3)] + [255])
png(OUT / 'help-wall.png', 32, 32, wall)
png(OUT / 'help-signs.png', 64, 96,
    b''.join(rgba(pixel(0x95, 484 << 6, x, y)) for y in range(96) for x in range(64)))
